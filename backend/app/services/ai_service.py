class AIService:
    def _strip_json_fence(self, text: str) -> str:
        text = (text or "").strip()
        if text.startswith("```"):
            lines = text.split("\n")
            if lines and lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].strip() == "```":
                lines = lines[:-1]
            text = "\n".join(lines).strip()
        return text

    def _extract_json_candidate(self, text: str) -> str:
        text = self._strip_json_fence(text)
        starts = [idx for idx in [text.find("{"), text.find("[")] if idx >= 0]
        if not starts:
            return text
        start = min(starts)
        opening = text[start]
        closing = "}" if opening == "{" else "]"
        depth = 0
        in_string = False
        escape = False
        end = -1
        for idx in range(start, len(text)):
            ch = text[idx]
            if in_string:
                if escape:
                    escape = False
                elif ch == "\\":
                    escape = True
                elif ch == "\"":
                    in_string = False
                continue
            if ch == "\"":
                in_string = True
            elif ch == opening:
                depth += 1
            elif ch == closing:
                depth -= 1
                if depth == 0:
                    end = idx + 1
                    break
        return text[start:end] if end > start else text[start:]

    def _escape_json_string_newlines(self, text: str) -> str:
        result = []
        in_string = False
        escape = False
        for ch in text:
            if in_string:
                if escape:
                    result.append(ch)
                    escape = False
                    continue
                if ch == "\\":
                    result.append(ch)
                    escape = True
                    continue
                if ch == "\"":
                    result.append(ch)
                    in_string = False
                    continue
                if ch == "\n":
                    result.append("\\n")
                    continue
                if ch == "\r":
                    result.append("\\r")
                    continue
                if ch == "\t":
                    result.append("\\t")
                    continue
                if ord(ch) < 32:
                    continue
                result.append(ch)
                continue
            result.append(ch)
            if ch == "\"":
                in_string = True
        return "".join(result)

    def _parse_json_text(self, text: str):
        candidate = self._extract_json_candidate(text)
        attempts = [
            candidate,
            re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", "", candidate),
            re.sub(r",\s*([}\]])", r"\1", candidate),
        ]
        attempts.append(self._escape_json_string_newlines(attempts[-1]))
        attempts.append(re.sub(r",\s*([}\]])", r"\1", attempts[-1]))
        last_error = None
        for item in attempts:
            try:
                return json.loads(item)
            except json.JSONDecodeError as exc:
                last_error = exc
        raise last_error or json.JSONDecodeError("Invalid JSON", candidate, 0)

    def _normalize_chinese_punctuation(self, text: str) -> str:
        text = text or ""
        text = re.sub(r"\.{3,}", "……", text)
        text = re.sub(r"…{3,}", "……", text)
        text = re.sub(r"—{3,}", "——", text)
        text = re.sub(r"[!！]{2,}", "！", text)
        text = re.sub(r"[?？]{2,}", "？", text)
        text = re.sub(r"[!！][?？]|[?？][!！]", "？！", text)
        text = re.sub(r"\s+([，。！？；：])", r"\1", text)

        replacements = {
            ",": "，",
            "?": "？",
            "!": "！",
            ";": "；",
        }
        for old, new in replacements.items():
            text = re.sub(rf"(?<=[\u4e00-\u9fff])\{old}", new, text)
            text = re.sub(rf"\{old}(?=[\u4e00-\u9fff])", new, text)
        text = re.sub(r"(?<=[\u4e00-\u9fff])\.(?=[\s\n]|$|[\u4e00-\u9fff])", "。", text)
        text = re.sub(r"(?<=[\u4e00-\u9fff]):(?=[\u4e00-\u9fff“”])", "：", text)
        text = re.sub(r"\"([^\"\n]*[\u4e00-\u9fff][^\"\n]*)\"", r"“\1”", text)
        text = re.sub(r"([\u4e00-\u9fff])\s+([“‘])", r"\1\2", text)
        text = re.sub(r"([”’])\s+([\u4e00-\u9fff])", r"\1\2", text)
        text = re.sub(r"([，；：])([。！？])", r"\2", text)
        text = re.sub(r"([。！？])([。！？])+", r"\1", text)
        return text

    def _clean_chapter_text(self, text: str) -> str:
        text = self._strip_json_fence(text)
        if text.startswith("{") or text.startswith("["):
            try:
                data = self._parse_json_text(text)
                if isinstance(data, dict) and "content" in data:
                    return self._clean_chapter_text(str(data.get("content") or ""))
                if isinstance(data, str):
                    return self._clean_chapter_text(data)
            except json.JSONDecodeError:
                pass
        return self._normalize_chinese_punctuation(text)

    async def _ask(self, prompt: str, system: str = SYSTEM_ARCHITECT, max_tokens: int | None = 128000, **kwargs) -> dict:
        llm = await get_llm()
        formatted = prompt.format(**kwargs)
        caller = inspect.currentframe().f_back
        function_name = kwargs.get("function_name") or (caller.f_code.co_name if caller else "_ask")
        project_name = kwargs.get("project_name") or kwargs.get("title") or kwargs.get("project_title") or ""
        project_id = kwargs.get("project_id") or ""
        task_id = kwargs.get("task_id") or ""
        with llm_call_context(function_name=function_name, project_name=project_name, project_id=project_id, task_id=task_id):
            try:
                return await llm.chat_json([LLMMessage(role="user", content=formatted)], system=system, max_tokens=max_tokens)
            except json.JSONDecodeError:
                resp = await llm.chat([LLMMessage(role="user", content=formatted)], system=system, temperature=0.7, max_tokens=max_tokens)
                content = self._strip_json_fence(resp.content)
                try:
                    return self._parse_json_text(content)
                except json.JSONDecodeError:
                    repair_prompt = JSON_REPAIR_PROMPT.format(content=content[:20000])
                    with llm_call_context(function_name=f"{function_name}.json_repair", project_name=project_name, project_id=project_id, task_id=task_id):
                        repair_resp = await llm.chat(
                            [LLMMessage(role="user", content=repair_prompt)],
                            system=SYSTEM_EDITOR,
                            temperature=0.1,
                            max_tokens=min(max_tokens or 16384, 16384),
                        )
                    repaired = self._strip_json_fence(repair_resp.content)
                    try:
                        return self._parse_json_text(repaired)
                    except json.JSONDecodeError:
                        raise RuntimeError(f"AI 返回格式异常，自动修复失败: {content[:300]}")

    async def _ask_list(self, prompt: str, system: str = SYSTEM_ARCHITECT, **kwargs) -> list[dict]:
        caller = inspect.currentframe().f_back
        if caller and not kwargs.get("function_name"):
            kwargs["function_name"] = caller.f_code.co_name
        result = await self._ask(prompt, system=system, **kwargs)
        if isinstance(result, list):
            return result
        for key in result:
            if isinstance(result[key], list):
                return result[key]
        return [result]

